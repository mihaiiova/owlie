/**
 * Prepares an arXiv HTML render (LaTeXML) for the generic article reader,
 * with plain string operations (no DOM, no scripts):
 *
 * - MathML is replaced by its LaTeX source (`alttext`), as `$…$` inline and
 *   `$$…$$` for display math, so formulas and numbers survive as text.
 * - The title, author block and abstract are removed: the arXiv document
 *   header already carries them, from the API.
 * - Footnote marks and their "thanks:" labels are removed; the footnote text
 *   stays.
 */
export function prepareLatexmlHtml(html: string): string {
  let prepared = html.replace(/<math\b([^>]*)>[\s\S]*?<\/math\s*>/gi, (match, attrs: string) => {
    const alttext = /\balttext="([^"]*)"/i.exec(attrs)?.[1];
    if (alttext === undefined) return match;
    return /\bdisplay="block"/i.test(attrs) ? ` $$${alttext}$$ ` : `$${alttext}$`;
  });
  for (const [tag, className] of FRONT_MATTER) prepared = removeElements(prepared, tag, className);
  return prepared
    .replace(/<sup\b[^>]*\bclass="[^"]*\bltx_note_mark\b[^"]*"[^>]*>[\s\S]*?<\/sup\s*>/gi, '')
    .replace(/<span\b[^>]*\bclass="[^"]*\bltx_note_type\b[^"]*"[^>]*>[\s\S]*?<\/span\s*>/gi, '');
}

const FRONT_MATTER: readonly [string, string][] = [
  ['h1', 'ltx_title_document'],
  ['div', 'ltx_authors'],
  ['div', 'ltx_abstract'],
];

/** Removes every `<tag class="… className …">` element with its (possibly nested) content. */
function removeElements(html: string, tag: string, className: string): string {
  const open = new RegExp(`<${tag}\\b[^>]*\\bclass="[^"]*\\b${className}\\b[^"]*"[^>]*>`, 'i');
  const token = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
  let result = html;
  for (;;) {
    const start = open.exec(result);
    if (!start) return result;
    token.lastIndex = start.index + start[0].length;
    let depth = 1;
    let end = result.length;
    for (let match = token.exec(result); match; match = token.exec(result)) {
      depth += match[1] ? -1 : 1;
      if (depth === 0) {
        end = match.index + match[0].length;
        break;
      }
    }
    result = result.slice(0, start.index) + result.slice(end);
  }
}

/** Whether an HTML page is a LaTeXML paper render (not an error or fallback page). */
export function isLatexmlRender(html: string): boolean {
  return /Generated by LaTeXML/i.test(html) || /class="ltx_document\b/.test(html);
}
